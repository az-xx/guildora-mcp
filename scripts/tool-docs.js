// Generates the tool reference in README.md from the built registry, so docs never drift.
// Usage: npm run build && npm run docs:tools        (rewrite README.md)
//        npm run docs:tools -- --check             (exit 1 if README.md is stale)
import { readFileSync, writeFileSync } from 'node:fs';

const { ALL_TOOLS } = await import('../dist/tools/registry.js');
const { PACK_NAMES, PACK_DESCRIPTIONS } = await import('../dist/tools/packs.js');

const START = '<!-- tools:start -->';
const END = '<!-- tools:end -->';

const firstSentence = (s) => {
  const m = /^(.+?\.)(\s|$)/.exec(s);
  return (m ? m[1] : s).replace(/\|/g, '\\|');
};

const sections = PACK_NAMES.map((pack) => {
  const tools = ALL_TOOLS.filter((t) => t.pack === pack);
  const rows = tools.map((t) => {
    const flag = t.destructive ? 'destructive' : t.readOnly ? 'read-only' : 'write';
    return `| \`${t.name}\` | ${flag} | ${firstSentence(t.description)} |`;
  });
  return [
    `#### \`${pack}\` (${tools.length} tools)${pack === 'core' ? ' · enabled by default' : ''}`,
    '',
    PACK_DESCRIPTIONS[pack] + '.',
    '',
    '| Tool | Kind | What it does |',
    '|---|---|---|',
    ...rows,
  ].join('\n');
});

const body = [
  START,
  `<!-- Generated by scripts/tool-docs.js. Do not edit by hand. -->`,
  '',
  `${ALL_TOOLS.length} tools in ${PACK_NAMES.length} packs.`,
  '',
  sections.join('\n\n'),
  END,
].join('\n');

const readme = readFileSync('README.md', 'utf8');
const start = readme.indexOf(START);
const end = readme.indexOf(END);
if (start === -1 || end === -1) {
  console.error('README.md is missing the tools markers.');
  process.exit(1);
}
const next = readme.slice(0, start) + body + readme.slice(end + END.length);

if (process.argv.includes('--check')) {
  if (next !== readme) {
    console.error(
      'README.md tool reference is out of date. Run: npm run build && npm run docs:tools',
    );
    process.exit(1);
  }
  console.log('README.md tool reference is up to date.');
} else {
  writeFileSync('README.md', next);
  console.log(`Wrote ${ALL_TOOLS.length} tools to README.md.`);
}
